package com.monkopedia.krapper.generator.model

import com.monkopedia.krapper.generator.model.type.WrappedType
import kotlinx.serialization.Transient

// Value equality is written out rather than generated by `data`: a data class's `copy()`
// would rebuild this element without its base-class provenance ([sourceLocation]), bypassing
// the final [clone] (#288).
class WrappedField(val name: String, val type: WrappedType) : WrappedElement() {
    // A per-instance identity token: WrappedField equals by value, so
    // the NameHandler uses this as a second, distinct map key when one field needs two
    // unique C names (getter + setter). Public because the namer lives in :krapper.
    @Transient
    val other = Any()

    override fun cloneImpl(): WrappedElement = WrappedField(name, type).also {
        it.addAllChildren(children)
        it.parent = parent
    }

    override fun toString(): String = "$name: $type"

    override fun equals(other: Any?): Boolean =
        other is WrappedField && name == other.name && type == other.type

    override fun hashCode(): Int = name.hashCode() * 31 + type.hashCode()
}
